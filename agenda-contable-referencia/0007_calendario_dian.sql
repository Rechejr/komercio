-- =========================================================
-- Calendario tributario DIAN 2026: fecha de vencimiento por
-- obligación, variante, periodo y último dígito del NIT.
--
-- Extraído del PDF oficial de la DIAN y verificado imagen por imagen.
-- Cubre: IVA bimestral, IVA cuatrimestral, retención en la fuente
-- (mensual) y renta personas jurídicas. Pendientes de otra pasada:
-- RST y renta personas naturales (esta última va por los DOS últimos
-- dígitos, no por uno, así que necesita otra columna/lógica).
--
-- `digito` = último dígito del NIT (0-9). `variante` distingue
-- bimestral/cuatrimestral en IVA y juridica/natural en renta; NULL
-- cuando la obligación no tiene variantes (retención).
-- =========================================================

CREATE TABLE calendario_dian (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    obligacion     TEXT NOT NULL,
    variante       TEXT,
    periodo        TEXT NOT NULL,
    periodo_orden  INTEGER NOT NULL,
    digito         INTEGER NOT NULL CHECK (digito BETWEEN 0 AND 9),
    fecha          TEXT NOT NULL
);

CREATE INDEX idx_calendario_lookup
    ON calendario_dian(obligacion, variante, digito);

